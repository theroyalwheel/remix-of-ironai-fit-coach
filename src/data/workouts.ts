export const CATEGORIES: Category[] = ["Strength", "Cardio", "Mobility"];
export const LEVELS: Level[] = ["Beginner", "Intermediate", "Advanced"];

export const MUSCLE_GROUPS = Array.from(
  new Set(WORKOUTS.flatMap((x) => x.muscles)),
).sort();

export function getWorkout(id: string): Workout | undefined {
  return WORKOUTS.find((x) => x.id === id);
}

export function searchWorkouts(
  query: string,
  category: Category | "All",
  level: Level | "All",
  muscle: string | "All",
): Workout[] {
  const q = query.trim().toLowerCase();
  return WORKOUTS.filter((x) => {
    if (category !== "All" && x.category !== category) return false;
    if (level !== "All" && x.level !== level) return false;
    if (muscle !== "All" && !x.muscles.includes(muscle)) return false;
    if (!q) return true;
    return (
      x.title.toLowerCase().includes(q) ||
      x.category.toLowerCase().includes(q) ||
      x.level.toLowerCase().includes(q) ||
      x.equipment.toLowerCase().includes(q) ||
      x.description.toLowerCase().includes(q) ||
      x.muscles.some((m) => m.toLowerCase().includes(q))
    );
  });
}
