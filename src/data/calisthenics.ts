  "Inhale on the lowering/easy phase, exhale through the effort. Never hold your breath through a full set.";
const DEFAULT_SAFETY =
  "Stop the set if you feel sharp or joint-line pain, dizziness or numbness. Muscular burn is fine, pain is not.";

function build(raw: Raw[]): CalExercise[] {
  return raw.map((r) => ({
    ...r,
    breathing: r.breathing ?? DEFAULT_BREATHING,
    safety: r.safety ?? DEFAULT_SAFETY,
    minutes: r.minutes ?? 4,
  }));
}

