export const CAL_BY_ID = new Map(CAL_EXERCISES.map((e) => [e.id, e]));

export function getCalExercise(id: string): CalExercise | undefined {
  return CAL_BY_ID.get(id);
}

export function getRoutine(id: string): Routine | undefined {
  return ROUTINES.find((r) => r.id === id);
}

export interface CalFilters {
  query?: string;
  category?: CalCategory | "All";
  level?: Level | "All";
  muscle?: CalMuscle | "All";
  pattern?: CalPattern | "All";
  goal?: CalGoal | "All";
  equipment?: "All" | "No equipment" | "Everywhere";
  maxMinutes?: number | null;
}

export function filterCalExercises(f: CalFilters): CalExercise[] {
  const q = (f.query ?? "").trim().toLowerCase();
  return CAL_EXERCISES.filter((e) => {
    if (f.category && f.category !== "All" && e.category !== f.category) return false;
    if (f.level && f.level !== "All" && e.level !== f.level) return false;
    if (f.pattern && f.pattern !== "All" && e.pattern !== f.pattern) return false;
    if (f.goal && f.goal !== "All" && !e.goals.includes(f.goal)) return false;
    if (f.muscle && f.muscle !== "All" && ![...e.primary, ...e.secondary].includes(f.muscle))
      return false;
    // "No equipment" = literally bodyweight/floor/wall.
    if (f.equipment === "No equipment" && e.equipment !== "None") return false;
    // "Everywhere" = also allows ordinary fixed structures.
    if (f.maxMinutes && e.minutes > f.maxMinutes) return false;
    if (!q) return true;
    const haystack = [
      e.name,
      e.category,
      e.level,
      e.pattern,
      e.summary,
      ...e.primary,
      ...e.secondary,
      ...e.goals,
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}

export function recommendCalRoutine(opts: {
  level: Level;
  minutes?: number;
  focus?: Routine["focus"];
  noEquipmentOnly?: boolean;
}): Routine {
  const pool = ROUTINES.filter((r) => (opts.noEquipmentOnly ? r.equipment === "None" : true));
  const scored = pool.map((r) => {
    let score = 0;
    if (r.level === opts.level) score += 3;
    else if (opts.level === "Intermediate" || r.level === "Intermediate") score += 1;
    if (opts.focus && r.focus === opts.focus) score += 3;
    if (opts.minutes) score += 3 - Math.min(3, Math.abs(r.minutes - opts.minutes) / 5);
    return { r, score };
  });
  scored.sort((a, b) => b.score - a.score);
  return (scored[0]?.r ?? ROUTINES[0]) as Routine;
}
